WITH lr AS (
  SELECT m.id AS report_id, l.subject, l.understanding_score, l.id AS lesson_id
  FROM tmp_map m
  JOIN public.weekly_reports w ON w.id = m.id
  JOIN public.lesson_records l ON l.student_id = w.student_id
   AND l.lesson_date BETWEEN '2026-07-27' AND '2026-08-02' AND l.submitted = true
), agg AS (
  SELECT report_id, count(*)::int AS total, round(avg(understanding_score)::numeric,2) AS avg_u FROM lr GROUP BY report_id
), subj AS (
  SELECT report_id, subject, round(avg(understanding_score)::numeric,2) AS a FROM lr GROUP BY report_id, subject
), sb AS (
  SELECT report_id, jsonb_agg(jsonb_build_object(
    'subject', subject,
    'avg_understanding', a,
    'note', CASE
      WHEN a IS NULL THEN '수업 참여 기록이 남아 있습니다'
      WHEN a >= 4.5 THEN '수업 내용을 안정적으로 따라오는 흐름이 보였습니다'
      WHEN a >= 3.5 THEN '전반적으로 수업 흐름을 잘 따라왔고, 일부 개념은 다시 짚어 볼 여지가 있었습니다'
      WHEN a >= 2.5 THEN '개념에 따라 이해 정도에 차이가 보여, 반복해서 확인할 부분이 남아 있었습니다'
      ELSE '개념을 소화하는 데 시간이 필요한 모습이 관찰되었습니다' END
  ) ORDER BY subject) AS breakdown
  FROM subj GROUP BY report_id
), hw AS (
  SELECT lr.report_id,
    count(*)::int AS total_hw,
    count(*) FILTER (WHERE h.result IN ('completed','low_effort_completed'))::int AS done_hw
  FROM lr JOIN public.homework_assignments h ON h.lesson_record_id = lr.lesson_id
  GROUP BY lr.report_id
)
UPDATE public.weekly_reports w
SET parent_message = p.t,
    student_message = '이번 주 수업에서 다룬 내용 중 다시 확인해 보면 좋을 부분이 있어요. 다음 수업에서 이어서 정리해 봐요.',
    summary = s.t,
    subject_breakdown = COALESCE(sb.breakdown, '[]'::jsonb),
    total_lessons = COALESCE(agg.total, 0),
    avg_understanding = agg.avg_u,
    homework_completion_rate = CASE WHEN hw.total_hw > 0 THEN round(hw.done_hw * 100.0 / hw.total_hw, 1) ELSE NULL END,
    generated_at = now(),
    parent_visible = false,
    sent_status = 'draft',
    parent_sent_status = 'draft',
    student_sent_status = 'draft',
    parent_sent_at = NULL,
    student_sent_at = NULL,
    sent_at = NULL
FROM tmp_map m
JOIN tmp_p p ON p.i = m.p
JOIN tmp_s s ON s.i = m.s
LEFT JOIN agg ON agg.report_id = m.id
LEFT JOIN sb ON sb.report_id = m.id
LEFT JOIN hw ON hw.report_id = m.id
WHERE w.id = m.id AND w.week_start = '2026-07-27' AND w.parent_visible = false AND w.sent_at IS NULL;

